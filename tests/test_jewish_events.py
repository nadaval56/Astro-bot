#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
בדיקות ל-get_jewish_events_today.

הרקע: ב-13.9.2026, במוצאי ראש השנה, נשלחה הודעה שקבעה "צום גדליה הסתיים"
בזמן שהצום טרם התחיל. הרשימה שהגיעה למודל הכילה את הצום פעמיים, בלי שום
ציון זמן, תחת כותרת שאמרה "היום". הבדיקות כאן מקבעות שכל אירוע נמסר פעם
אחת ועם הזמן שבו הוא באמת חל.
"""
from helpers import S, Results, freeze


def events(ts: str) -> str:
    freeze(ts)
    return "\n".join(S.get_jewish_events_today())


def main() -> None:
    r = Results("🕯️ לוח יהודי – אירועים וזמניהם")

    # ── המקרה שנשבר: מוצאי ראש השנה, הצום רק מחר בבוקר ──
    got = events("2026-09-13 21:00")
    r.check("מוצאי ר\"ה 21:00 – נאמר שהצום עדיין לא התחיל",
            got, "עדיין לא התחיל")
    r.check("מוצאי ר\"ה 21:00 – מצוין שהוא מתחיל בעלות השחר",
            got, "עלות השחר")
    r.check("מוצאי ר\"ה 21:00 – הצום מופיע פעם אחת בלבד",
            str(got.count("צום גדליה")), "1")
    assert "הסתיים" not in got, "אסור שיופיע 'הסתיים' בערב שלפני הצום"

    # ── ריצת יום ביום הצום עצמו – קודם הצום לא הוזכר כלל ──
    got = events("2026-09-14 16:30")
    r.check("יום הצום 16:30 – הצום מוזכר ומצוין כמתקיים",
            got, "בעיצומו")
    r.check("יום הצום 16:30 – מצוין שהוא מסתיים הערב",
            got, "מסתיים הערב")

    # ── ערב הצום בריצת יום ──
    r.check("13.9 בצהריים – הצום מוצג כמחר",
            events("2026-09-13 16:30"), "מחר")

    # ── חגים נכנסים בשקיעה ──
    r.check("ערב ר\"ה 16:30 – החג נכנס הערב",
            events("2026-09-11 16:30"), "ראש השנה – נכנס הערב עם השקיעה")
    r.check("ליל ר\"ה 21:00 – החג חל עכשיו",
            events("2026-09-11 21:00"), "ראש השנה – חל עכשיו")
    r.check("ערב יום כיפור 16:30 – נכנס הערב",
            events("2026-09-20 16:30"), "יום כיפור – נכנס הערב עם השקיעה")

    # ── צום בן 25 שעות מתחיל בשקיעה ולא בעלות השחר ──
    got = events("2027-08-11 21:00")
    r.check("ליל ט' באב – הצום התחיל עם השקיעה",
            got, "התחיל עכשיו עם השקיעה")
    r.check("ליל ט' באב – הצום מופיע פעם אחת בלבד",
            str(got.count("ט׳ באב")), "1")
    r.check("ט' באב בצהריים – הצום בעיצומו",
            events("2027-08-12 16:30"), "בעיצומו")

    # ── ראש חודש ──
    r.check("ראש חודש חשוון בערב – מוכרז עם 'חודש טוב'",
            events("2026-10-11 21:00"), "ראש חודש חשון")

    # א' תשרי הוא ראש חודש, אך ראש השנה גובר ולא מאחלים "חודש טוב"
    got = events("2026-09-11 21:00")
    assert "ראש חודש" not in got, \
        f"אין להכריז ראש חודש בראש השנה, התקבל: {got}"
    r.check("ליל ר\"ה – אין הכרזת ראש חודש",
            "אין ראש חודש", "אין ראש חודש")

    # ── יום חול רגיל – שתיקה ──
    got = events("2026-09-16 21:00")
    assert got == "", f"ביום חול הרשימה חייבת להיות ריקה, התקבל: {got}"
    r.check("יום חול רגיל – אין אירועים", "ריק", "ריק")

    r.done()


if __name__ == "__main__":
    main()
