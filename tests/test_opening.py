#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
בדיקות לברכת הפתיחה (fix_opening) – בעיקר חול המועד.

בחול המועד ההודעה נפתחת ב"מועדים לשמחה" במקום ברכה לפי השעה.
"""
from helpers import S, Results, freeze


def opening(ts: str, first_line: str, is_motzei: bool = False) -> str:
    freeze(ts)
    payload = {"jdate": S.get_jewish_date_info(), "is_motzei": is_motzei}
    msg = S.fix_opening(f"{first_line}\n27.9.2026 | גוף ההודעה", payload)
    return msg.split("\n", 1)[0]


def main() -> None:
    r = Results("👋 ברכת פתיחה")

    r.check("חוה\"מ סוכות בצהריים – 'צהריים טובים' מוחלף",
            opening("2026-09-28 16:30", "צהריים טובים ☀️"), "מועדים לשמחה")
    r.check("חוה\"מ סוכות בלילה – 'לילה טוב' מוחלף",
            opening("2026-09-28 21:30", "לילה טוב 🌙"), "מועדים לשמחה 🌙")
    r.check("חוה\"מ – פתיחה נכונה נשארת",
            opening("2026-09-28 21:30", "מועדים לשמחה 🌙"), "מועדים לשמחה 🌙")
    got = opening("2027-04-22 21:00", "שבוע טוב ✨", is_motzei=True)
    r.check("מוצאי יו\"ט ראשון של פסח ביום חמישי – מועדים לשמחה, לא שבוע טוב",
            got, "מועדים לשמחה ✨")
    assert not got.startswith("שבוע טוב"), f"יום חמישי אינו מוצאי שבת: {got}"
    r.check("מוצאי יו\"ט ראשון של סוכות שחל בשבת – שבוע טוב ומועדים לשמחה",
            opening("2026-09-26 21:00", "לילה טוב ✨", is_motzei=True),
            "שבוע טוב ומועדים לשמחה ✨")
    r.check("מוצאי שבת חוה\"מ פסח – שבוע טוב ומועדים לשמחה",
            opening("2027-04-24 21:00", "שבוע טוב ✨", is_motzei=True),
            "שבוע טוב ומועדים לשמחה ✨")
    r.check("מוצאי שבת חוה\"מ – פתיחה נכונה נשארת כמות שהיא",
            opening("2027-04-24 21:00", "שבוע טוב ומועדים לשמחה ✨", is_motzei=True),
            "שבוע טוב ומועדים לשמחה ✨")
    r.check("מוצאי שבת רגיל – 'שבוע טוב ומועדים לשמחה' מתוקן ל'שבוע טוב'",
            opening("2026-10-10 21:00", "שבוע טוב ומועדים לשמחה ✨", is_motzei=True),
            "שבוע טוב ✨")
    r.check("הושענא רבה בצהריים – מועדים לשמחה",
            opening("2026-10-02 14:00", "צהריים טובים ☀️"), "מועדים לשמחה")
    r.check("חוה\"מ פסח – מועדים לשמחה",
            opening("2027-04-24 21:30", "לילה טוב 🌙"), "מועדים לשמחה")

    # מחוץ לחול המועד – ההתנהגות הרגילה לא השתנתה
    r.check("יום חול רגיל בצהריים – צהריים טובים",
            opening("2026-10-06 14:00", "מועדים לשמחה ☀️"), "צהריים טובים")
    r.check("מוצאי שמחת תורה – שבוע טוב וחורף טוב",
            opening("2026-10-03 21:00", "שבוע טוב 🌙", is_motzei=True),
            "שבוע טוב וחורף טוב 🌙")
    got = opening("2026-10-03 21:00", "שבוע טוב ומועדים לשמחה 🌙", is_motzei=True)
    r.check("מוצאי שמחת תורה – אין 'מועדים לשמחה'", got, "שבוע טוב וחורף טוב")
    assert "מועדים" not in got, f"במוצאי שמחת תורה אין מועדים לשמחה: {got}"
    r.check("מוצאי שמחת תורה – פתיחה נכונה נשארת",
            opening("2026-10-03 21:00", "שבוע טוב וחורף טוב 🌙", is_motzei=True),
            "שבוע טוב וחורף טוב 🌙")
    r.check("מוצאי שבת אחרי שמחת תורה – 'וחורף טוב' מתוקן ל'שבוע טוב'",
            opening("2026-10-10 21:00", "שבוע טוב וחורף טוב 🌙", is_motzei=True),
            "שבוע טוב 🌙")
    r.check("ערב סוכות בצהריים – צהריים טובים",
            opening("2026-09-25 14:00", "צהריים טובים ☀️"), "צהריים טובים")

    r.done()


if __name__ == "__main__":
    main()
